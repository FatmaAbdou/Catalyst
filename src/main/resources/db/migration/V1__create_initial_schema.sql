-- Enforce that every donation has exactly the subtype row matching donation_type.
-- Deferred checks allow the DONATIONS row and its subtype row to be inserted in the
-- same transaction, in either order.
CREATE OR REPLACE FUNCTION check_donation_subtype_consistency()
RETURNS TRIGGER AS $$
DECLARE
    target_donation_id INTEGER;
    target_type VARCHAR(10);
    monetary_count INTEGER;
    in_kind_count INTEGER;
BEGIN
    IF TG_TABLE_NAME = 'donations' THEN
        target_donation_id := COALESCE(NEW.donation_id, OLD.donation_id);
    ELSIF TG_OP = 'DELETE' THEN
        target_donation_id := OLD.donation_id;
    ELSE
        target_donation_id := NEW.donation_id;
    END IF;

    SELECT donation_type INTO target_type
    FROM donations WHERE donation_id = target_donation_id;

    -- The donation may have been deleted in this transaction.
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    SELECT COUNT(*) INTO monetary_count
    FROM monetary_donations WHERE donation_id = target_donation_id;

    SELECT COUNT(*) INTO in_kind_count
    FROM in_kind_donations WHERE donation_id = target_donation_id;

    IF target_type = 'MONETARY' AND (monetary_count <> 1 OR in_kind_count <> 0) THEN
        RAISE EXCEPTION 'Donation % must have exactly one MONETARY_DONATIONS row and no IN_KIND_DONATIONS row', target_donation_id;
    ELSIF target_type = 'IN_KIND' AND (in_kind_count <> 1 OR monetary_count <> 0) THEN
        RAISE EXCEPTION 'Donation % must have exactly one IN_KIND_DONATIONS row and no MONETARY_DONATIONS row', target_donation_id;
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER ct_donations_subtype_consistency
AFTER INSERT OR UPDATE ON donations
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION check_donation_subtype_consistency();

CREATE CONSTRAINT TRIGGER ct_monetary_donations_subtype_consistency
AFTER INSERT OR UPDATE OR DELETE ON monetary_donations
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION check_donation_subtype_consistency();

CREATE CONSTRAINT TRIGGER ct_in_kind_donations_subtype_consistency
AFTER INSERT OR UPDATE OR DELETE ON in_kind_donations
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION check_donation_subtype_consistency();
