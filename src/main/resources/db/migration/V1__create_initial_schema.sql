-- Catalyst initial PostgreSQL schema
-- Based on Catalyst_ERD_MultiPage(1).drawio
-- All primary/foreign key identifiers use INTEGER as specified in the ERD.

-- 1. Accounts and roles
CREATE TABLE users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    contact_info VARCHAR(255),
    preferred_channel VARCHAR(10) CHECK (preferred_channel IN ('EMAIL', 'SMS')),
    status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE roles (
    role_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE user_roles (
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    role_id INTEGER NOT NULL REFERENCES roles(role_id) ON DELETE RESTRICT,
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE donors (
    donor_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER UNIQUE REFERENCES users(user_id) ON DELETE SET NULL,
    donor_name VARCHAR(200) NOT NULL,
    donor_type VARCHAR(20) NOT NULL CHECK (donor_type IN ('INDIVIDUAL', 'ORGANIZATION')),
    contact_info VARCHAR(255)
);

CREATE TABLE volunteer_profiles (
    volunteer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
    preferences TEXT
);

-- 2. Assistance categories and campaigns
CREATE TABLE assistance_categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE campaigns (
    campaign_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER NOT NULL REFERENCES assistance_categories(category_id) ON DELETE RESTRICT,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    fundraising_target NUMERIC(12, 2),
    status VARCHAR(12) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'ACTIVE', 'COMPLETED')),
    CONSTRAINT chk_campaign_dates CHECK (end_date >= start_date),
    CONSTRAINT chk_campaign_target CHECK (fundraising_target IS NULL OR fundraising_target >= 0)
);

-- 3. Donations
CREATE TABLE donations (
    donation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_id INTEGER NOT NULL REFERENCES donors(donor_id) ON DELETE RESTRICT,
    campaign_id INTEGER REFERENCES campaigns(campaign_id) ON DELETE SET NULL,
    donation_reference VARCHAR(80) NOT NULL UNIQUE,
    donation_type VARCHAR(10) NOT NULL CHECK (donation_type IN ('MONETARY', 'IN_KIND')),
    donation_date DATE NOT NULL
);

CREATE TABLE monetary_donations (
    donation_id INTEGER PRIMARY KEY REFERENCES donations(donation_id) ON DELETE CASCADE,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    payment_method VARCHAR(10) NOT NULL CHECK (payment_method IN ('CASH', 'CHECK', 'ONLINE'))
);

CREATE TABLE in_kind_donations (
    donation_id INTEGER PRIMARY KEY REFERENCES donations(donation_id) ON DELETE CASCADE,
    item_description TEXT NOT NULL,
    quantity NUMERIC(12, 3) NOT NULL CHECK (quantity > 0),
    unit VARCHAR(50) NOT NULL,
    condition VARCHAR(100)
);

-- 4. Events and registrations (payment_transactions is created after registrations)
CREATE TABLE events (
    event_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id INTEGER REFERENCES campaigns(campaign_id) ON DELETE SET NULL,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    location VARCHAR(255) NOT NULL,
    starts_at TIMESTAMP NOT NULL,
    ends_at TIMESTAMP NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    ticket_price NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (ticket_price >= 0),
    status VARCHAR(12) NOT NULL DEFAULT 'UPCOMING'
        CHECK (status IN ('UPCOMING', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT chk_event_times CHECK (ends_at > starts_at)
);

CREATE TABLE event_registrations (
    registration_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id INTEGER NOT NULL REFERENCES events(event_id) ON DELETE RESTRICT,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    registration_status VARCHAR(12) NOT NULL DEFAULT 'PENDING'
        CHECK (registration_status IN ('PENDING', 'CONFIRMED', 'CANCELLED')),
    ticket_reference VARCHAR(80) UNIQUE,
    registered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- A user may register again after cancelling, but cannot have two non-cancelled
-- registrations for the same event.
CREATE UNIQUE INDEX uq_event_registration_active
    ON event_registrations(event_id, user_id)
    WHERE registration_status <> 'CANCELLED';

CREATE TABLE attendance (
    attendance_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_id INTEGER NOT NULL UNIQUE
        REFERENCES event_registrations(registration_id) ON DELETE CASCADE,
    attended BOOLEAN NOT NULL,
    recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- A payment attempt belongs to exactly one donation OR one event registration.
CREATE TABLE payment_transactions (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donation_id INTEGER REFERENCES donations(donation_id) ON DELETE RESTRICT,
    registration_id INTEGER REFERENCES event_registrations(registration_id) ON DELETE RESTRICT,
    provider_reference VARCHAR(150),
    payment_method VARCHAR(30) NOT NULL,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'CONFIRMED', 'FAILED')),
    transaction_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_payment_exactly_one_owner CHECK (
        (donation_id IS NOT NULL AND registration_id IS NULL)
        OR (donation_id IS NULL AND registration_id IS NOT NULL)
    )
);

-- 5. Volunteer management
CREATE TABLE skills (
    skill_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_name VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE volunteer_skills (
    volunteer_id INTEGER NOT NULL
        REFERENCES volunteer_profiles(volunteer_id) ON DELETE CASCADE,
    skill_id INTEGER NOT NULL REFERENCES skills(skill_id) ON DELETE RESTRICT,
    PRIMARY KEY (volunteer_id, skill_id)
);

CREATE TABLE volunteer_availability (
    availability_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    volunteer_id INTEGER NOT NULL
        REFERENCES volunteer_profiles(volunteer_id) ON DELETE CASCADE,
    availability_details TEXT NOT NULL
);

CREATE TABLE volunteer_tasks (
    task_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id INTEGER REFERENCES campaigns(campaign_id) ON DELETE SET NULL,
    event_id INTEGER REFERENCES events(event_id) ON DELETE SET NULL,
    description TEXT NOT NULL,
    starts_at TIMESTAMP NOT NULL,
    ends_at TIMESTAMP NOT NULL,
    CONSTRAINT chk_task_times CHECK (ends_at > starts_at),
    CONSTRAINT chk_task_campaign_or_event CHECK (campaign_id IS NOT NULL OR event_id IS NOT NULL)
);

CREATE TABLE task_required_skills (
    task_id INTEGER NOT NULL REFERENCES volunteer_tasks(task_id) ON DELETE CASCADE,
    skill_id INTEGER NOT NULL REFERENCES skills(skill_id) ON DELETE RESTRICT,
    PRIMARY KEY (task_id, skill_id)
);

CREATE TABLE volunteer_assignments (
    assignment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id INTEGER NOT NULL REFERENCES volunteer_tasks(task_id) ON DELETE RESTRICT,
    volunteer_id INTEGER NOT NULL REFERENCES volunteer_profiles(volunteer_id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'ASSIGNED',
    assigned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_task_volunteer UNIQUE (task_id, volunteer_id)
);

CREATE TABLE service_records (
    service_record_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id INTEGER NOT NULL REFERENCES volunteer_assignments(assignment_id) ON DELETE RESTRICT,
    service_date DATE NOT NULL,
    hours NUMERIC(6, 2) NOT NULL CHECK (hours > 0)
);

-- 6. Beneficiaries and assistance
CREATE TABLE beneficiaries (
    beneficiary_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beneficiary_reference VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    contact_info VARCHAR(255),
    household_size INTEGER NOT NULL CHECK (household_size > 0)
);

CREATE TABLE beneficiary_needs (
    beneficiary_id INTEGER NOT NULL
        REFERENCES beneficiaries(beneficiary_id) ON DELETE CASCADE,
    category_id INTEGER NOT NULL
        REFERENCES assistance_categories(category_id) ON DELETE RESTRICT,
    need_description TEXT,
    PRIMARY KEY (beneficiary_id, category_id)
);

CREATE TABLE assistance_distributions (
    assistance_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beneficiary_id INTEGER NOT NULL
        REFERENCES beneficiaries(beneficiary_id) ON DELETE RESTRICT,
    category_id INTEGER NOT NULL
        REFERENCES assistance_categories(category_id) ON DELETE RESTRICT,
    campaign_id INTEGER REFERENCES campaigns(campaign_id) ON DELETE SET NULL,
    assistance_date DATE NOT NULL,
    assistance_type VARCHAR(10) NOT NULL CHECK (assistance_type IN ('MONETARY', 'IN_KIND')),
    amount NUMERIC(12, 2),
    quantity NUMERIC(12, 3),
    unit VARCHAR(50),
    description TEXT,
    CONSTRAINT chk_assistance_value CHECK (
        (assistance_type = 'MONETARY' AND amount IS NOT NULL AND amount > 0
            AND quantity IS NULL AND unit IS NULL)
        OR
        (assistance_type = 'IN_KIND' AND amount IS NULL
            AND quantity IS NOT NULL AND quantity > 0 AND unit IS NOT NULL)
    )
);

CREATE TABLE follow_up_notes (
    note_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beneficiary_id INTEGER NOT NULL
        REFERENCES beneficiaries(beneficiary_id) ON DELETE CASCADE,
    staff_user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    note_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    note TEXT NOT NULL
);

-- 7. Communications: one row per recipient/delivery, allowing one publication
-- to create many rows (one for each selected recipient).
CREATE TABLE communications (
    communication_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id INTEGER REFERENCES users(user_id) ON DELETE RESTRICT,
    recipient_donor_id INTEGER REFERENCES donors(donor_id) ON DELETE RESTRICT,
    recipient_beneficiary_id INTEGER REFERENCES beneficiaries(beneficiary_id) ON DELETE RESTRICT,
    channel VARCHAR(10) NOT NULL CHECK (channel IN ('EMAIL', 'SMS')),
    message_content TEXT NOT NULL,
    sent_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sending_status VARCHAR(20) NOT NULL
        CHECK (sending_status IN ('PENDING', 'SENT', 'FAILED')),
    CONSTRAINT chk_communication_exactly_one_recipient CHECK (
        num_nonnulls(recipient_user_id, recipient_donor_id, recipient_beneficiary_id) = 1
    )
);

-- Useful indexes for common foreign-key lookups and history screens.
CREATE INDEX idx_donations_donor_id ON donations(donor_id);
CREATE INDEX idx_donations_campaign_id ON donations(campaign_id);
CREATE INDEX idx_events_campaign_id ON events(campaign_id);
CREATE INDEX idx_event_registrations_user_id ON event_registrations(user_id);
CREATE INDEX idx_volunteer_assignments_volunteer_id ON volunteer_assignments(volunteer_id);
CREATE INDEX idx_assistance_beneficiary_date ON assistance_distributions(beneficiary_id, assistance_date);
CREATE INDEX idx_communications_sent_at ON communications(sent_at);
CREATE INDEX idx_communications_recipient_user ON communications(recipient_user_id);
CREATE INDEX idx_communications_recipient_donor ON communications(recipient_donor_id);
CREATE INDEX idx_communications_recipient_beneficiary ON communications(recipient_beneficiary_id);

